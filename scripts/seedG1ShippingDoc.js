const apply = process.argv.includes("--apply");

async function main() {
  const ref = db.doc("meta/g1ShippingDoc");
  const existing = await ref.get();
  if (existing.exists) {
    console.log("[注意] meta/g1ShippingDoc は既に存在します。実行すると上書きされます。");
  }

  console.log(`セクション数: ${sections.length}`);
  for (const s of sections) {
    console.log(`  - ${s.title}（${s.rows.length}行）`);
  }

  if (!apply) {
    console.log("---");
    console.log("dry-runです。実際に書き込むには --apply を付けて再実行してください。");
    return;
  }

  await ref.set({
    sections,
    updatedAt: new Date().toISOString(),
    updatedBy: "初期投入（スクリプト）",
  });
  console.log("meta/g1ShippingDoc に書き込みました。");
}

main().then(() => process.exit(0)).catch((err) => {
  console.error(err);
  process.exit(1);
});
